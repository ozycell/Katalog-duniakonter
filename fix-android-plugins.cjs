#!/usr/bin/env node
/**
 * Fix Capacitor Android plugin registration files.
 * Run this after `npx cap sync android` because Capacitor CLI v7
 * cannot auto-detect plugins when used with Capacitor v8 core.
 */

const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const ANDROID_DIR = path.join(PROJECT_ROOT, 'android');
const APP_DIR = path.join(ANDROID_DIR, 'app');

const PLUGINS = [
  { pkg: '@capacitor/app', dir: 'node_modules/@capacitor/app/android', className: 'com.capacitorjs.plugins.app.AppPlugin' },
  { pkg: '@capacitor/barcode-scanner', dir: 'node_modules/@capacitor/barcode-scanner/android', className: 'com.capacitorjs.barcodescanner.CapacitorBarcodeScannerPlugin' },
  { pkg: '@capacitor/camera', dir: 'node_modules/@capacitor/camera/android', className: 'com.capacitorjs.plugins.camera.CameraPlugin' },
  { pkg: '@capacitor/clipboard', dir: 'node_modules/@capacitor/clipboard/android', className: 'com.capacitorjs.plugins.clipboard.ClipboardPlugin' },
  { pkg: '@capacitor/filesystem', dir: 'node_modules/@capacitor/filesystem/android', className: 'com.capacitorjs.plugins.filesystem.FilesystemPlugin' },
  { pkg: '@capacitor/keyboard', dir: 'node_modules/@capacitor/keyboard/android', className: 'com.capacitorjs.plugins.keyboard.KeyboardPlugin' },
  { pkg: '@capacitor/local-notifications', dir: 'node_modules/@capacitor/local-notifications/android', className: 'com.capacitorjs.plugins.localnotifications.LocalNotificationsPlugin' },
  { pkg: '@capacitor/share', dir: 'node_modules/@capacitor/share/android', className: 'com.capacitorjs.plugins.share.SharePlugin' },
  { pkg: '@capacitor/status-bar', dir: 'node_modules/@capacitor/status-bar/android', className: 'com.capacitorjs.plugins.statusbar.StatusBarPlugin' },
  { pkg: '@capacitor-community/contacts', dir: 'node_modules/@capacitor-community/contacts/android', className: 'getcapacitor.community.contacts.ContactsPlugin' },
  { pkg: '@capawesome/capacitor-google-sign-in', dir: 'node_modules/@capawesome/capacitor-google-sign-in/android', className: 'io.capawesome.capacitorjs.plugins.googlesignin.GoogleSignInPlugin' },
  { pkg: '@ascentio-it/capacitor-bluetooth-serial', dir: 'node_modules/@ascentio-it/capacitor-bluetooth-serial/android', className: 'com.bluetoothserial.plugin.BluetoothSerialPlugin' },
];

function generateSettingsGradle() {
  const lines = [
    '// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN',
    "include ':capacitor-android'",
    "project(':capacitor-android').projectDir = new File('../node_modules/@capacitor/android/capacitor')",
  ];

  for (const p of PLUGINS) {
    const moduleName = p.pkg.replace('@', '').replace('/', '-');
    lines.push(`\ninclude ':${moduleName}'`);
    lines.push(`project(':${moduleName}').projectDir = new File('../${p.dir}')`);
  }

  return lines.join('\n') + '\n';
}

function generateBuildGradle() {
  const lines = [
    '// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN',
    '',
    'android {',
    '  compileOptions {',
    '      sourceCompatibility JavaVersion.VERSION_21',
    '      targetCompatibility JavaVersion.VERSION_21',
    '  }',
    '}',
    '',
    'apply from: "../capacitor-cordova-android-plugins/cordova.variables.gradle"',
    'dependencies {',
  ];

  for (const p of PLUGINS) {
    const moduleName = p.pkg.replace('@', '').replace('/', '-');
    lines.push(`    implementation project(':${moduleName}')`);
  }

  lines.push('}');
  lines.push('');
  lines.push("if (hasProperty('postBuildExtras')) {");
  lines.push('    postBuildExtras()');
  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

function generatePluginsJson() {
  const entries = PLUGINS.map(p => ({
    pkg: p.pkg,
    classpath: p.className,
  }));
  return JSON.stringify(entries, null, '\t') + '\n';
}

function writeFile(filePath, content) {
  fs.writeFileSync(filePath, content, 'utf-8');
  console.log(`✓ ${path.relative(PROJECT_ROOT, filePath)}`);
}

console.log('Fixing Capacitor Android plugin registration files...\n');

writeFile(path.join(ANDROID_DIR, 'capacitor.settings.gradle'), generateSettingsGradle());
writeFile(path.join(APP_DIR, 'capacitor.build.gradle'), generateBuildGradle());
writeFile(path.join(APP_DIR, 'src/main/assets/capacitor.plugins.json'), generatePluginsJson());

console.log('\nDone! Run the following to rebuild:');
console.log('  cd android && ./gradlew assembleDebug');
